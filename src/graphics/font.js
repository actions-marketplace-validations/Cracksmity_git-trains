const SPACE = 2;
export const GLYPH_H = 5;

// Remove accents and keep only what the font can draw.
export function clean(text) {
  return String(text)
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9\-.,:/+_# %]/g, '');
}

export function textWidth(text) {
  const t = clean(text);
  if (!t) return 0;
  let w = 0;
  for (const ch of t) w += (ch === ' ' ? SPACE : 3) + 1;
  return w - 1;
}

// Draw the text and return the width used.
export function drawText(grid, text, x, y, color) {
  const t = clean(text);
  let cx = x;
  for (const ch of t) {
    if (ch === ' ') {
      cx += SPACE + 1;
      continue;
    }
    const g = GLYPHS[ch];
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < 3; c++) if (g[r][c] === '#') grid.set(cx + c, y + r, color);
    }
    cx += 4;
  }
  return cx - x - 1;
}
